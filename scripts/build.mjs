import { readFile, writeFile } from 'node:fs/promises';
import { pages, pageFile } from './pages.mjs';

// Content lives in one bilingual file. Every page uses this shared template.
const root = new URL('../', import.meta.url);
const content = JSON.parse(await readFile(new URL('content.json', root), 'utf8'));
const escape = (value) => String(value).replace(/[&<>"']/g, (char) => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
}[char]));

for (const lang of ['en', 'ja']) {
  const text = (value) => {
    const translation = typeof value === 'string' ? value : value?.[lang];
    if (typeof translation !== 'string') throw new Error(`Missing ${lang} translation: ${JSON.stringify(value)}`);
    return escape(translation);
  };
  const label = (key) => text(content.labels[key]);
  const link = (url, title) => {
    if (!/^(https:\/\/|mailto:)/.test(url)) throw new Error(`Unsupported link: ${url}`);
    return `<a href="${escape(url)}">${text(title)}</a>`;
  };
  const entries = (items, heading = 'h2') => items.map((item) => `
          <li>
            <${heading} class="entry-title">${text(item.title)}</${heading}>
            <p>${text(item.description)}</p>
          </li>`).join('');
  const profile = content.profile;
  const bodies = {
    home: `<div class="intro">
        <p>${text(profile.intro)}</p>
        <p>${text(profile.aside)}</p>
        <ul class="contact-links" aria-label="${lang === 'en' ? 'Find me online' : 'リンク・連絡先'}">
          ${profile.links.map((item) => `<li>${link(item.url, item.label)}</li>`).join('\n          ')}
          <li>${link(`mailto:${profile.email}`, profile.email)}</li>
        </ul>
      </div>`,
    research: content.research.map((item) => `<article>
        <h2 class="entry-title">${text(item.title)}</h2>
        <p>${text(item.description)}</p>
        <p class="note">${text(item.note)}</p>
      </article>`).join('\n      '),
    projects: `<ul class="entry-list projects">${content.projects.map((item) => `
        <li>
          <h2 class="entry-title">${link(item.url, item.title)} <span class="outward" aria-hidden="true">↗</span></h2>
          <p>${text(item.description)}</p>
          <p class="note">${text(item.tools)}</p>
        </li>`).join('')}
      </ul>`,
    awards: `<ul class="entry-list">${entries(content.background)}
      </ul>
      <section class="achievements" aria-labelledby="achievements-heading">
        <h2 id="achievements-heading">${label('achievements')}</h2>
        <ul class="entry-list">${entries(content.achievements, 'h3')}
        </ul>
      </section>
      <details>
        <summary>${label('more')}</summary>
        <ul class="entry-list">${entries(content.earlier)}
        </ul>
      </details>`,
    skills: `<ul class="entry-list skills-groups">${content.about.map((group) => `
        <li>
          <h2 class="entry-title">${text(group.title)}</h2>
          <ul class="skill-points">${group.items.map((item) => `
            <li><strong>${text(item.label)}:</strong> ${text(item.text)}</li>`).join('')}
          </ul>
        </li>`).join('')}
      </ul>`,
  };

  for (const page of pages) {
    const file = pageFile(page, lang);
    const home = pageFile(pages[0], lang);
    const html = `<!DOCTYPE html>
<!-- Generated by npm run build. Edit content.json, scripts/build.mjs, or style.css. -->
<html lang="${lang}">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <meta name="description" content="${text(profile.intro)}" />
  <title>${page.id === 'home' ? '' : `${label(page.id)} · `}${text(profile.name)}</title>
  <link rel="stylesheet" href="style.css" />
  <link rel="alternate" hreflang="en" href="${pageFile(page, 'en')}" />
  <link rel="alternate" hreflang="ja" href="${pageFile(page, 'ja')}" />
</head>
<body>
  <a class="skip-link" href="#main">${label('skip')}</a>
  <div class="page" id="top">
    <div class="page-top">
      <a class="handle" href="${home}">${text(profile.handle)}</a>
      <nav class="languages" aria-label="${label('language')}">
        <a href="${pageFile(page, 'en')}" lang="en" hreflang="en"${lang === 'en' ? ' aria-current="page"' : ''}>English</a>
        <span aria-hidden="true">/</span>
        <a href="${pageFile(page, 'ja')}" lang="ja" hreflang="ja"${lang === 'ja' ? ' aria-current="page"' : ''}>日本語</a>
      </nav>
    </div>

    <header>
        <div class="identity">
          ${page.id === 'home' ? `<h1>${text(profile.name)}</h1>` : `<a class="site-name" href="${home}">${text(profile.name)}</a>`}
          <img class="mascot" src="${escape(encodeURI(profile.mascot))}" alt="${text(profile.mascotAlt)}" width="88" height="104" draggable="false" />
        </div>
      <nav class="sections" aria-label="${label('navigation')}">
        ${pages.map((target) => `<a href="${pageFile(target, lang)}"${target.id === page.id ? ' aria-current="page"' : ''}>${label(target.id)}</a>`).join('\n        ')}
      </nav>
    </header>

    <main id="main" class="page-content">
${page.id === 'home' ? '' : `      <h1 class="page-heading">${label(page.id)}</h1>\n`}      ${bodies[page.id]}
    </main>

    <footer>
      <span>${text(profile.handle)}</span>
      <a href="#top">${label('top')}</a>
    </footer>
  </div>
</body>
</html>
`;
    await writeFile(new URL(file, root), html);
    console.log(`Built ${file}`);
  }
}
